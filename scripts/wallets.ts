// Generates the five TESTNET wallets the demo uses and writes them to .env (gitignored).
// Never reuse these keys for anything holding real money, and never commit .env.
import { existsSync, writeFileSync } from "node:fs"
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts"

if (existsSync(".env") && !process.argv.includes("--force")) {
  console.error(".env already exists. Re-run with --force to overwrite (old keys will be lost).")
  process.exit(1)
}
const roles = ["STEWARD", "HOSPITAL_1", "HOSPITAL_2", "DONOR", "IMPOSTER"] as const
let env = "# Rakt Relay TESTNET keys. Generated by `npm run wallets`. NEVER commit this file.\n"
env += "# Fund ONLY the steward from https://hub.arkiv.network/faucet ; `npm run seed` shares GLM with the others.\n"
env += "# Optional: ARKIV_RPC_URL=https://rpc.tiramisu.db-chain.testnet.arkiv.network/<your-access-key>\n"
for (const r of roles) {
  const pk = generatePrivateKey()
  env += `${r}_KEY=${pk}\n`
  console.log(`${r.padEnd(11)} ${privateKeyToAccount(pk).address}`)
}
writeFileSync(".env", env, { mode: 0o600 })
console.log("\nWrote .env. Next: paste the STEWARD address into the faucet, then run `npm run seed`.")
